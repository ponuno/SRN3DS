@dataclass(frozen=True)
class TexturePolicy:
    """Build policy for one texture.

    ``max_dim`` is the PICA limit (1024 on the 3DS).  ``min_mip_dim`` matches
    the renderer, which does not store mips below 8x8.
    """

    max_dim: int = 1024
    min_mip_dim: int = 8
    alpha_mode: str = "auto"       # auto | force | drop
    mip_mode: str = "source"       # source | generate
    max_memory_bytes: int = 16 * 1024 * 1024
    max_output_bytes: int = 0      # 0 = no output cap
    require_power_of_two: bool = True
    quality: str = "high"          # tex3ds -q low|medium|high

    def validate(self) -> None:
        if self.max_dim < 8 or self.max_dim & (self.max_dim - 1):
            raise TextureError("max_dim must be a power of two >= 8")
        if self.min_mip_dim < 1 or self.min_mip_dim & (self.min_mip_dim - 1):
            raise TextureError("min_mip_dim must be a power of two >= 1")
        if self.alpha_mode not in ("auto", "force", "drop"):
            raise TextureError("alpha_mode must be auto, force or drop")
        if self.mip_mode not in ("source", "generate"):
            raise TextureError("mip_mode must be source or generate")
        if self.quality not in ("low", "medium", "high"):
            raise TextureError("quality must be low, medium or high")
        if self.max_memory_bytes <= 0 or self.max_output_bytes < 0:
            raise TextureError("invalid byte budget")



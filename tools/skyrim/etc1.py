@dataclass
class ConversionResult:
    plan: TexturePlan
    container_path: str
    container_bytes: int
    memory: dict
    quality: dict
    level_sizes: List[dict]
    output_sha256: str

    def as_dict(self) -> dict:
        out = self.plan.as_dict()
        out.update({
            "container_path": self.container_path,
            "container_bytes": self.container_bytes,
            "memory": self.memory,
            "quality": self.quality,
            "level_sizes": self.level_sizes,
            "output_sha256": self.output_sha256,
        })
        return out


def _write_png_temp(path: str, w: int, h: int, rgba: bytes) -> int:
    # Imported lazily so the planning path does not depend on the PNG writer.
    from .convert import write_png
    return write_png(path, w, h, rgba)


def convert_texture(data: bytes, name: str, out_dir: str,
                    policy: Optional[TexturePolicy] = None,
                    tex3ds: Optional[str] = None,
                    keep_png: bool = False) -> ConversionResult:
    """Convert one DDS surface to an SKTX ETC1/ETC1A4 container.

    Memory is bounded by decoding one source mip at a time.  ``data`` itself
    is already resident (the caller read it from the BSA); the meter counts it
    so the report is honest about the simultaneous source + decoded copy.
    """
    policy = policy or TexturePolicy()
    policy.validate()
    plan = plan_texture(data, name, policy, require_payload=True)
    info = dds_mod.parse_dds(data)
    safe = name.replace("\\", "_").replace("/", "_")
    os.makedirs(out_dir, exist_ok=True)
    temp_dir = os.path.join(out_dir, "_tmp_" + safe)
    os.makedirs(temp_dir, exist_ok=True)
    meter = MemoryMeter(limit=policy.max_memory_bytes)
    meter.acquire("source_dds", len(data), "source")
    level_payloads: List[Tuple[int, int, bytes]] = []
    level_sizes: List[dict] = []
    quality: dict = {}
    try:
        # Decode the entry level once.  It is either the source top mip (small
        # enough) or the first source mip at or below max_dim.
        entry = plan.levels[0]
        if entry.width != info.levels[entry.source_level].width or \
                entry.height != info.levels[entry.source_level].height:
            raise TextureError("%s: entry level dimensions disagree" % name)
        sw, sh, rgba = dds_mod.decode_level(data, info, entry.source_level)
        if (sw, sh) != (entry.width, entry.height):
            raise TextureError("%s: decoded %dx%d, planned %dx%d" %
                               (name, sw, sh, entry.width, entry.height))
        meter.acquire("rgba", len(rgba), "decode level %d" % entry.level)
        if plan.alpha_dropped:
            rgba = _drop_alpha(rgba)
        png = os.path.join(temp_dir, "level0.png")
        png_bytes = _write_png_temp(png, sw, sh, rgba)
        meter.acquire("png", png_bytes, "write png level 0")
        raw_path = os.path.join(temp_dir, "level0.bin")
        fmt = plan.chosen_format
        mip_arg = "box" if policy.mip_mode == "generate" else None
        _run_tex3ds(png, raw_path, fmt, policy.quality,
                    mipmap=mip_arg, tex3ds=tex3ds)
        expected_total = sum(
            l.etc1a4_bytes if fmt == "etc1a4" else l.etc1_bytes
            for l in plan.levels)
        expected0 = entry.etc1a4_bytes if fmt == "etc1a4" else entry.etc1_bytes
        payload = _parse_raw(raw_path, expected_total if mip_arg else expected0)
        if mip_arg:
            # tex3ds generated the whole chain from the top level.  Split by
            # the expected size of each level.
            pos = 0
            for level in plan.levels:
                size = level.etc1a4_bytes if fmt == "etc1a4" else level.etc1_bytes
                if pos + size > len(payload):
                    raise TextureError("%s: generated mip chain is truncated" % name)
                level_payloads.append((level.width, level.height,
                                       payload[pos:pos + size]))
                level_sizes.append({"level": level.level, "width": level.width,
                                    "height": level.height, "bytes": size,
                                    "source": "tex3ds -m box"})
                pos += size
            if pos != len(payload):
                raise TextureError("%s: generated mip chain has %d trailing bytes" %
                                   (name, len(payload) - pos))
            meter.acquire("raw", len(payload), "encode generated mips")
        else:
            meter.acquire("raw", len(payload), "encode level 0")
            level_payloads.append((entry.width, entry.height, payload))
            level_sizes.append({"level": 0, "width": entry.width,
                                "height": entry.height, "bytes": len(payload),
                                "source": "source mip %d" % entry.source_level})
        # Quality: decode the encoder's top-level blocks, not the thumbnail
        # preview tex3ds writes for humans (that preview is capped at 256x256
        # and would make a 512x1024 PSNR meaningless).
        top = level_payloads[0][2]
        decoded = decode_etc1_image(top, entry.width, entry.height,
                                    alpha=(fmt == "etc1a4"))
        quality = quality_report(rgba, decoded, entry.width, entry.height)
        quality["alpha"] = {
            "source_bits": plan.alpha_source_bits,
            "output_bits": 4 if fmt == "etc1a4" else 0,
            "dropped": plan.alpha_dropped,
            "note": ("ETC1 has no alpha" if fmt == "etc1" else
                     "ETC1A4 alpha is 4-bit (16 levels, step 17, max "
                     "round-trip error 8), not BC3's 8-bit alpha"),
        }
        quality["top_level_encoded_bytes"] = len(top)
        quality["measurement"] = "decoded ETC1 top level vs decoded source mip"

        # Remaining source mips.  For source mode we decode one at a time; if
        # the source chain ended early, box-filter the previous RGBA so the
        # output still has a complete PICA chain (documented in the report).
        if not mip_arg:
            prev_rgba = rgba
            prev_w, prev_h = entry.width, entry.height
            meter.release("png")
            meter.release("raw")
            for level in plan.levels[1:]:
                if level.width * 2 == prev_w and level.height * 2 == prev_h:
                    # Prefer the stored source mip when it matches the target.
                    src_level = level.source_level
                    if src_level < len(info.levels) and \
                            info.levels[src_level].width == level.width and \
                            info.levels[src_level].height == level.height:
                        w, h, level_rgba = dds_mod.decode_level(data, info, src_level)
                        source_note = "source mip %d" % src_level
                    else:
                        w, h, level_rgba = _half_rgba(prev_rgba, prev_w, prev_h)
                        source_note = "box-filtered from level %d" % (level.level - 1)
                else:
                    w, h, level_rgba = _half_rgba(prev_rgba, prev_w, prev_h)
                    source_note = "box-filtered from level %d" % (level.level - 1)
                if (w, h) != (level.width, level.height):
                    raise TextureError("%s: level %d is %dx%d, planned %dx%d" %
                                       (name, level.level, w, h,
                                        level.width, level.height))
                meter.replace("rgba", len(level_rgba), "decode level %d" % level.level)
                if plan.alpha_dropped:
                    level_rgba = _drop_alpha(level_rgba)
                png = os.path.join(temp_dir, "level%d.png" % level.level)
                png_bytes = _write_png_temp(png, w, h, level_rgba)
                meter.replace("png", png_bytes, "write png level %d" % level.level)
                raw = os.path.join(temp_dir, "level%d.bin" % level.level)
                _run_tex3ds(png, raw, fmt, policy.quality, tex3ds=tex3ds)
                expected = level.etc1a4_bytes if fmt == "etc1a4" else level.etc1_bytes
                payload = _parse_raw(raw, expected)
                meter.replace("raw", len(payload), "encode level %d" % level.level)
                level_payloads.append((w, h, payload))
                level_sizes.append({"level": level.level, "width": w, "height": h,
                                    "bytes": len(payload), "source": source_note})
                prev_rgba, prev_w, prev_h = level_rgba, w, h
                meter.release("png")
                meter.release("raw")
                if not keep_png:
                    for p in (png, raw):
                        try:
                            os.remove(p)
                        except OSError:
                            pass
        container_path = os.path.join(out_dir, safe + ".sktx")
        container_bytes = write_sktx(container_path, entry.width, entry.height,
                                     fmt, level_payloads)
        meter.acquire("container", container_bytes, "write container")
        sha = hashlib.sha256(open(container_path, "rb").read()).hexdigest()
        result = ConversionResult(
            plan=plan, container_path=container_path,
            container_bytes=container_bytes, memory=meter.as_dict(),
            quality=quality, level_sizes=level_sizes, output_sha256=sha)
        return result
    finally:
        if not keep_png:
            shutil.rmtree(temp_dir, ignore_errors=True)



"""Production DDS/BC -> ETC1 pipeline for the 3DS texture budget.

This is host-side build tooling.  It never writes game bytes into the
repository: callers pass DDS bytes read from the retail archives and the
derived ``.sktx`` / JSON files live under ``E:\\Skyrim_N3DS_build``.

What is real here
-----------------
* BC1/BC2/BC3 are decoded one mip at a time by :mod:`skyrim.dds`.
* ETC1/ETC1A4 blocks are produced by devkitPro ``tex3ds`` (the same encoder the
  build uses); this module does not pretend to be an encoder.
* Mip chains are either preserved level-by-level from the source DDS or
  regenerated by tex3ds from the top level.  The default preserves source
  levels because Bethesda's mips are already filtered.
* Dimensions above PICA's 1024 limit are entered at a source mip instead of
  decoding a 4096x4096 RGBA buffer.  That bounds host memory and is explicit
  in the conversion report.
* The output is the small ``SKTX`` container below, not a lossless claim:
  ETC1 is 4 bpp RGB and ETC1A4 adds 4-bit alpha.  BC3 colour+alpha is 8 bpp
  and its alpha is 8-bit, so ETC1A4 is *not* equivalent to BC3.

The container is deliberately simple and is parsed by
``source/d3d9_texcache.c``'s sibling loader tests (see docs/TEXTURES.md):

    offset  size  field
    0       4     "SKTX"
    4       4     u32 version (1)
    8       2     u16 format (0 = ETC1, 1 = ETC1A4)
    10      2     u16 levels
    12      2     u16 width
    14      2     u16 height
    16      4     u32 data_bytes
    20      4     u32 crc32 of level data (zlib crc32)
    24      12*n  level table: u16 w, u16 h, u32 offset, u32 bytes
    ...           level data, PICA-tiled ETC1/ETC1A4 as emitted by tex3ds -r

Offsets in the level table are absolute file offsets.  Level data for
ETC1A4 is 16 bytes per 4x4 block; ETC1 is 8 bytes per block.

Bounded memory
--------------
``MemoryMeter`` tracks the live host buffers the pipeline owns.  It does not
count the tex3ds process's own heap (that is outside this process); the
reported peak is therefore a lower bound on total host memory, and the
documentation says so.  A policy can cap this value; the converter fails with a
deterministic :class:`TextureBudgetError` instead of silently swapping or
allocating an unbounded RGBA surface.

Quality
-------
``convert`` decodes the encoder's raw top-level ETC1/ETC1A4 blocks and compares
RGB PSNR/max error against the decoded source mip.  Both all-pixel and
visible-pixel (source alpha >= 8) figures are reported, because an ETC1A4
encoder may discard RGB hidden by zero alpha.  Alpha quality is reported
analytically (4-bit alpha = 16 levels, step 17, max round-trip error 8), not as
a pixel PSNR; ETC1A4 is not BC3.
"""


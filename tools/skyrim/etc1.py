def _pow2(value: int) -> bool:
    return value > 0 and not (value & (value - 1))


def _log2(value: int) -> int:
    return value.bit_length() - 1


def _etc1_level_bytes(w: int, h: int, alpha: bool) -> int:
    return ((w + 3) // 4) * ((h + 3) // 4) * (16 if alpha else 8)


def _mip_dims(width: int, height: int, min_dim: int) -> List[Tuple[int, int]]:
    """Mip dimensions the renderer can store, top first.

    The rule mirrors ``d3d9_core.c``: stop before either dimension falls below
    ``min_dim``.  This is why a 1024x1024 surface has 8 levels (down to 8x8),
    not 11.
    """
    out: List[Tuple[int, int]] = []
    w, h = width, height
    while w >= min_dim and h >= min_dim:
        out.append((w, h))
        if w == 1 and h == 1:
            break
        w = max(1, w >> 1)
        h = max(1, h >> 1)
    return out


def _scan_bc1_alpha(data: bytes, info: dds_mod.DdsInfo) -> bool:
    """True when a BC1 top level uses the c0<=c1 punch-through mode.

    BC1's three-colour mode is not alpha; the fourth colour is transparent only
    when c0 <= c1.  Scanning the top level is enough for a production decision
    and avoids decoding pixels.
    """
    if info.kind != "bc1" or not info.levels:
        return False
    lv = info.levels[0]
    bw = (lv.width + 3) // 4
    bh = (lv.height + 3) // 4
    start = lv.offset
    end = min(len(data), lv.offset + lv.size)
    for by in range(bh):
        for bx in range(bw):
            pos = start + (by * bw + bx) * 8
            if pos + 4 > end:
                return False
            c0, c1 = struct.unpack_from("<HH", data, pos)
            if c0 <= c1:
                return True
    return False


def plan_texture(data: bytes, name: str,
                 policy: Optional[TexturePolicy] = None,
                 require_payload: bool = True) -> TexturePlan:
    """Plan one DDS surface without decoding its pixels."""
    policy = policy or TexturePolicy()
    policy.validate()
    try:
        info = dds_mod.parse_dds(data, require_payload=require_payload)
    except dds_mod.DdsError as exc:
        raise TextureError("%s: %s" % (name, exc)) from exc
    if policy.require_power_of_two and (not _pow2(info.width) or not _pow2(info.height)):
        raise TextureError(
            "%s: %dx%d is not power-of-two; PICA tiling and this pipeline "
            "require power-of-two dimensions" % (name, info.width, info.height))
    if policy.max_dim > 1024:
        raise TextureError("PICA max_dim cannot exceed 1024")

    max_source = max(info.width, info.height)
    start_level = max(0, _log2((max_source + policy.max_dim - 1) // policy.max_dim)) \
        if max_source > policy.max_dim else 0
    # A source mip at start_level may be missing; clamp to the stored chain.
    start_level = min(start_level, max(0, len(info.levels) - 1))
    target_w = max(1, info.width >> start_level)
    target_h = max(1, info.height >> start_level)

    dims = _mip_dims(target_w, target_h, policy.min_mip_dim)
    if not dims:
        raise TextureError("%s: no PICA-storable mip dimensions" % name)

    needs_alpha = info.kind in ("bc2", "bc3")
    alpha_bits = 8 if info.kind in ("bc2", "bc3") else 0
    if info.kind == "bc1":
        if require_payload and len(data) >= dds_mod.DDS_DATA_OFFSET:
            needs_alpha = _scan_bc1_alpha(data, info)
            alpha_bits = 1 if needs_alpha else 0

    if policy.alpha_mode == "force":
        chosen = "etc1a4"
    elif policy.alpha_mode == "drop":
        chosen = "etc1"
    else:
        chosen = "etc1a4" if needs_alpha else "etc1"
    alpha_dropped = bool(needs_alpha and chosen == "etc1")

    levels: List[LevelPlan] = []
    for level, (w, h) in enumerate(dims):
        source_level = min(start_level + level, max(0, len(info.levels) - 1))
        src = info.levels[source_level]
        levels.append(LevelPlan(
            level=level, source_level=source_level, width=w, height=h,
            source_width=src.width, source_height=src.height,
            source_bytes=src.size,
            etc1_bytes=_etc1_level_bytes(w, h, False),
            etc1a4_bytes=_etc1_level_bytes(w, h, True),
        ))

    chosen_bytes = sum(l.etc1a4_bytes if chosen == "etc1a4" else l.etc1_bytes
                       for l in levels)
    container_bytes = SKTX_HEADER + SKTX_LEVEL * len(levels) + chosen_bytes
    # Peak while encoding one level: full source DDS + the largest source mip
    # decoded to RGBA + its PNG + the encoded level we are holding.  The source
    # DDS is counted once; the BSA reader may hold its own copy outside us.
    max_src = max(l.source_bytes for l in levels) if levels else 0
    max_rgba = max(l.width * l.height * 4 for l in levels) if levels else 0
    max_png = int(max_rgba * 0.65) + 4096
    max_raw = max(l.etc1a4_bytes for l in levels) if levels else 0
    estimated_peak = len(data) + max_src + max_rgba + max_png + max_raw
    if estimated_peak > policy.max_memory_bytes:
        raise TextureBudgetError(
            "%s: estimated host peak %d B exceeds max_memory_bytes %d "
            "(source %d, mip %d, rgba %d, png %d, raw %d)" %
            (name, estimated_peak, policy.max_memory_bytes, len(data),
             max_src, max_rgba, max_png, max_raw))
    if policy.max_output_bytes and container_bytes > policy.max_output_bytes:
        raise TextureBudgetError(
            "%s: %s container %d B exceeds max_output_bytes %d" %
            (name, chosen.upper(), container_bytes, policy.max_output_bytes))

    return TexturePlan(
        name=name, source_format=info.format_name, source_kind=info.kind,
        width=info.width, height=info.height, source_mips=len(info.levels),
        source_bytes=info.all_mips_size,
        target_width=target_w, target_height=target_h,
        start_level=start_level, levels=levels,
        needs_alpha=needs_alpha, alpha_source_bits=alpha_bits,
        chosen_format=chosen, chosen_bytes=chosen_bytes,
        container_bytes=container_bytes,
        estimated_peak_bytes=estimated_peak,
        downscaled=(target_w != info.width or target_h != info.height),
        alpha_dropped=alpha_dropped, mip_mode=policy.mip_mode, policy=policy)



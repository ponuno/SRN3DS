def project_inventory(rows: Iterable[dict], max_dim: int = 1024) -> dict:
    """Project the real inventory through this pipeline's policies.

    ``rows`` is ``textures.json`` from ``tools/skyrim/report.py`` (header
    derived).  No pixels are decoded.  The projection explicitly counts files
    that exceed PICA's dimension limit and would be entered at a lower mip.
    """
    total = etc1_drop = etc1a4_all = mixed = 0
    alpha = over = 0
    formats: Dict[str, int] = {}
    for row in rows:
        total += 1
        fmt = row.get("format", "?")
        formats[fmt] = formats.get(fmt, 0) + 1
        w, h = int(row.get("width", 0)), int(row.get("height", 0))
        start = 0
        while max(w >> start, h >> start) > max_dim:
            start += 1
        tw, th = max(1, w >> start), max(1, h >> start)
        needs = bool(row.get("needs_alpha"))
        if needs:
            alpha += 1
        if start:
            over += 1
        levels = _mip_dims(tw, th, 8)
        rgb = sum(_etc1_level_bytes(lw, lh, False) for lw, lh in levels)
        a4 = sum(_etc1_level_bytes(lw, lh, True) for lw, lh in levels)
        etc1_drop += rgb
        etc1a4_all += a4
        mixed += a4 if needs else rgb
    return {
        "textures": total,
        "formats": dict(sorted(formats.items())),
        "needs_alpha": alpha,
        "downscaled_to_max_dim": over,
        "max_dim": max_dim,
        "etc1_alpha_dropped_bytes": etc1_drop,
        "etc1a4_all_bytes": etc1a4_all,
        "mixed_auto_bytes": mixed,
        "note": ("Surface bytes only, PICA mip chain (8x8 minimum), no "
                 "container headers.  This is a header-derived projection, not "
                 "a conversion.  needs_alpha comes from the inventory's format "
                 "classification; BC1 punch-through files are not decoded here, "
                 "so the mixed figure can undercount those as ETC1."),
    }

def _half_rgba(rgba: bytes, w: int, h: int) -> Tuple[int, int, bytes]:
    """2x2 box filter with integer rounding, top-down RGBA8."""
    nw, nh = max(1, w // 2), max(1, h // 2)
    out = bytearray(nw * nh * 4)
    for y in range(nh):
        for x in range(nw):
            acc = [0, 0, 0, 0]
            count = 0
            for dy in range(2):
                sy = min(h - 1, y * 2 + dy)
                for dx in range(2):
                    sx = min(w - 1, x * 2 + dx)
                    p = (sy * w + sx) * 4
                    for c in range(4):
                        acc[c] += rgba[p + c]
                    count += 1
            o = (y * nw + x) * 4
            for c in range(4):
                out[o + c] = (acc[c] + count // 2) // count
    return nw, nh, bytes(out)


def _drop_alpha(rgba: bytes) -> bytes:
    out = bytearray(rgba)
    for i in range(3, len(out), 4):
        out[i] = 255
    return bytes(out)



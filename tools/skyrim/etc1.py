def find_tex3ds(explicit: Optional[str] = None) -> str:
    if explicit:
        if os.path.isfile(explicit):
            return explicit
        raise TextureError("tex3ds not found at %s" % explicit)
    for env in ("TEX3DS", "SKYRIM_TEX3DS"):
        value = os.environ.get(env)
        if value:
            if os.path.isfile(value):
                return value
            raise TextureError("%s points at %s, which is not a file" % (env, value))
    found = shutil.which("tex3ds") or shutil.which("tex3ds.exe")
    if found:
        return found
    for candidate in (r"C:\devkitPro\tools\bin\tex3ds.exe",
                      "/opt/devkitpro/tools/bin/tex3ds"):
        if os.path.isfile(candidate):
            return candidate
    raise TextureError("tex3ds not found; install devkitPro or set TEX3DS")


def _run_tex3ds(png: str, out: str, fmt: str, quality: str,
                mipmap: Optional[str] = None,
                tex3ds: Optional[str] = None,
                timeout: int = 180) -> None:
    exe = find_tex3ds(tex3ds)
    args = [exe, "-f", fmt, "-z", "none", "-r", "-q", quality,
            "-o", out]
    if mipmap:
        args += ["-m", mipmap]
    args.append(png)
    result = subprocess.run(args, capture_output=True, text=True, check=False,
                            timeout=timeout)
    if result.returncode != 0:
        raise TextureError("tex3ds failed (%d): %s" %
                           (result.returncode,
                            (result.stderr or result.stdout).strip()))


def _parse_raw(path: str, expected: int) -> bytes:
    """Return the ETC1 block payload from a tex3ds ``-r`` file.

    tex3ds writes a small 4-byte prefix before the blocks.  Its encoding is
    not a stable public format (observed values are not a plain u32 for the
    smallest surfaces), so the pipeline validates against the *expected* PICA
    block size instead.  That is deterministic for ETC1 (8 bytes/block) and
    ETC1A4 (16 bytes/block) and rejects a truncated or padded file.
    """
    with open(path, "rb") as handle:
        data = handle.read()
    if not expected:
        raise TextureError("internal: raw parser needs an expected byte count")
    if len(data) == expected:
        return data
    if len(data) == expected + 4:
        return data[4:]
    raise TextureError(
        "tex3ds raw output %s is %d bytes, expected %d (+4-byte prefix)" %
        (path, len(data), expected))


def write_sktx(path: str, width: int, height: int, fmt: str,
               levels: Sequence[Tuple[int, int, bytes]]) -> int:
    """Write the documented SKTX container; returns file bytes."""
    if fmt not in ("etc1", "etc1a4"):
        raise TextureError("unknown SKTX format %s" % fmt)
    if not levels:
        raise TextureError("SKTX needs at least one level")
    data_bytes = sum(len(level[2]) for level in levels)
    table_bytes = SKTX_LEVEL * len(levels)
    offset = SKTX_HEADER + table_bytes
    table = bytearray()
    payload = bytearray()
    for w, h, raw in levels:
        table += struct.pack("<HHII", w, h, offset, len(raw))
        payload += raw
        offset += len(raw)
    header = bytearray(SKTX_MAGIC)
    header += struct.pack("<IHHHHII", SKTX_VERSION,
                          SKTX_FORMAT_ETC1A4 if fmt == "etc1a4" else SKTX_FORMAT_ETC1,
                          len(levels), width, height, data_bytes,
                          zlib.crc32(bytes(payload)) & 0xFFFFFFFF)
    blob = bytes(header) + bytes(table) + bytes(payload)
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(blob)
    return len(blob)


def read_sktx(data: bytes) -> dict:
    """Validate and parse an SKTX container (used by tests and the C loader)."""
    if len(data) < SKTX_HEADER or data[:4] != SKTX_MAGIC:
        raise TextureError("not an SKTX container")
    version, fmt, levels, width, height, data_bytes, crc = struct.unpack_from(
        "<IHHHHII", data, 4)
    if version != SKTX_VERSION:
        raise TextureError("unsupported SKTX version %d" % version)
    if fmt not in (SKTX_FORMAT_ETC1, SKTX_FORMAT_ETC1A4):
        raise TextureError("unsupported SKTX format %d" % fmt)
    if levels == 0 or levels > 16:
        raise TextureError("implausible SKTX level count %d" % levels)
    table_end = SKTX_HEADER + SKTX_LEVEL * levels
    if table_end > len(data):
        raise TextureError("SKTX level table is truncated")
    out_levels = []
    for i in range(levels):
        w, h, offset, size = struct.unpack_from("<HHII", data,
                                                SKTX_HEADER + i * SKTX_LEVEL)
        if offset < table_end or offset + size > len(data):
            raise TextureError("SKTX level %d is outside the file" % i)
        expected = ((w + 3) // 4) * ((h + 3) // 4) * (
            16 if fmt == SKTX_FORMAT_ETC1A4 else 8)
        if size != expected:
            raise TextureError(
                "SKTX level %d has %d bytes, expected %d for %dx%d %s" %
                (i, size, expected, w, h,
                 "ETC1A4" if fmt == SKTX_FORMAT_ETC1A4 else "ETC1"))
        out_levels.append({"width": w, "height": h, "offset": offset,
                           "bytes": size})
    payload = b"".join(data[l["offset"]:l["offset"] + l["bytes"]]
                       for l in out_levels)
    if len(payload) != data_bytes:
        raise TextureError("SKTX data_bytes does not match the level table")
    if zlib.crc32(payload) & 0xFFFFFFFF != crc:
        raise TextureError("SKTX crc32 mismatch")
    return {
        "format": "etc1a4" if fmt == SKTX_FORMAT_ETC1A4 else "etc1",
        "width": width, "height": height, "levels": out_levels,
        "data_bytes": data_bytes,
    }



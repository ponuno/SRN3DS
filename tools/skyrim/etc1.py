@dataclass
class MemoryMeter:
    """Tracks live host buffers owned by the conversion of one texture."""

    limit: int = 0
    live: Dict[str, int] = field(default_factory=dict)
    peak: int = 0
    peak_live: Dict[str, int] = field(default_factory=dict)
    peak_event: str = ""
    total_allocated: int = 0

    def _check(self, event: str) -> None:
        total = sum(self.live.values())
        if total > self.peak:
            self.peak = total
            self.peak_live = dict(self.live)
            self.peak_event = event
        if self.limit and total > self.limit:
            raise TextureBudgetError(
                "%s: live host bytes %d exceed limit %d (%s)" %
                (event, total, self.limit, ", ".join(
                    "%s=%d" % item for item in sorted(self.live.items()))))

    def acquire(self, tag: str, bytes_: int, event: str) -> None:
        if bytes_ < 0:
            raise TextureBudgetError("negative allocation for " + tag)
        self.live[tag] = self.live.get(tag, 0) + bytes_
        self.total_allocated += bytes_
        self._check(event)

    def release(self, tag: str) -> None:
        self.live.pop(tag, None)

    def replace(self, tag: str, bytes_: int, event: str) -> None:
        self.release(tag)
        self.acquire(tag, bytes_, event)

    def as_dict(self) -> dict:
        return {
            "peak_bytes": self.peak,
            "peak_live": dict(sorted(self.peak_live.items())),
            "peak_event": self.peak_event,
            "total_allocated_bytes": self.total_allocated,
            "current_bytes": sum(self.live.values()),
        }


# ---------------------------------------------------------------------------
# ETC1 decoder (quality measurement only; tex3ds is still the encoder)
# ---------------------------------------------------------------------------

_ETC1_MODIFIERS = (
    2, 8, -2, -8, 5, 17, -5, -17, 9, 29, -9, -29, 13, 42, -13, -42,
    18, 60, -18, -60, 24, 80, -24, -80, 33, 106, -33, -106, 47, 183, -47, -183,
)
_ETC1_LOOKUP = (0, 1, 2, 3, -4, -3, -2, -1)


def decode_etc1_block(block: bytes) -> List[Tuple[int, int, int, int]]:
    """Decode one 8-byte ETC1 colour block to 16 RGBA tuples (raster 4x4)."""
    if len(block) < 8:
        raise TextureError("ETC1 block is shorter than 8 bytes")
    # tex3ds/PICA store the 64-bit ETC1 word little-endian.  Reading the first
    # four bytes as the high word (the usual GL convention) decodes red blocks
    # as blue, which is exactly the mistake this comment prevents.
    value = int.from_bytes(block[:8], "little")
    high = (value >> 32) & 0xFFFFFFFF
    low = value & 0xFFFFFFFF

    diff = high & 2
    flip = high & 1
    cw1 = (high >> 5) & 7
    cw2 = (high >> 2) & 7
    if diff:
        r1 = (high >> 27) & 0x1F
        dr = (high >> 24) & 0x7
        g1 = (high >> 19) & 0x1F
        dg = (high >> 16) & 0x7
        b1 = (high >> 11) & 0x1F
        db = (high >> 8) & 0x7
        r2 = (r1 + _ETC1_LOOKUP[dr]) & 0x1F
        g2 = (g1 + _ETC1_LOOKUP[dg]) & 0x1F
        b2 = (b1 + _ETC1_LOOKUP[db]) & 0x1F
        r1 = (r1 << 3) | (r1 >> 2)
        g1 = (g1 << 3) | (g1 >> 2)
        b1 = (b1 << 3) | (b1 >> 2)
        r2 = (r2 << 3) | (r2 >> 2)
        g2 = (g2 << 3) | (g2 >> 2)
        b2 = (b2 << 3) | (b2 >> 2)
    else:
        r1 = ((high >> 28) & 0xF) * 17
        r2 = ((high >> 24) & 0xF) * 17
        g1 = ((high >> 20) & 0xF) * 17
        g2 = ((high >> 16) & 0xF) * 17
        b1 = ((high >> 12) & 0xF) * 17
        b2 = ((high >> 8) & 0xF) * 17
    out: List[Tuple[int, int, int, int]] = [(0, 0, 0, 255)] * 16
    for index in range(8):
        if flip:
            x = index >> 1
            y = index & 1
        else:
            x = index >> 2
            y = index & 3
        k = y + x * 4
        sel = ((low >> k) & 1) | ((low >> (k + 15)) & 2)
        delta = _ETC1_MODIFIERS[(cw1 << 2) + sel]
        out[y * 4 + x] = (
            min(255, max(0, r1 + delta)),
            min(255, max(0, g1 + delta)),
            min(255, max(0, b1 + delta)), 255)
    for index in range(8):
        if flip:
            x = index >> 1
            y = (index & 1) + 2
        else:
            x = (index >> 2) + 2
            y = index & 3
        k = y + x * 4
        sel = ((low >> k) & 1) | ((low >> (k + 15)) & 2)
        delta = _ETC1_MODIFIERS[(cw2 << 2) + sel]
        out[y * 4 + x] = (
            min(255, max(0, r2 + delta)),
            min(255, max(0, g2 + delta)),
            min(255, max(0, b2 + delta)), 255)
    return out


def decode_etc1_image(data: bytes, width: int, height: int,
                      alpha: bool = False) -> bytes:
    """Decode a PICA-tiled ETC1/ETC1A4 level to top-down RGBA8.

    The 3DS stores ETC1 in 8x8-pixel tiles; each tile contains four 4x4 blocks
    in quadrant order.  tex3ds ``-r`` emits exactly that layout.  For ETC1A4
    the 8-byte alpha plane precedes the 8-byte colour block in each 16-byte
    block; this function decodes the colour and forces alpha to 255 because the
    quality report treats alpha analytically.
    """
    block_size = 16 if alpha else 8
    bw, bh = (width + 3) // 4, (height + 3) // 4
    need = bw * bh * block_size
    if len(data) < need:
        raise TextureError("ETC1 image is truncated (%d of %d bytes)" %
                           (len(data), need))
    out = bytearray(width * height * 4)
    tiles_x = (width + 7) // 8
    tiles_y = (height + 7) // 8
    for ty in range(tiles_y):
        for tx in range(tiles_x):
            for q in range(4):
                bx = tx * 2 + (q & 1)
                by = ty * 2 + (q >> 1)
                if bx >= bw or by >= bh:
                    continue
                index = (ty * tiles_x + tx) * 4 + q
                off = index * block_size
                color = data[off + (8 if alpha else 0):
                             off + (16 if alpha else 8)]
                pixels = decode_etc1_block(color)
                for py in range(4):
                    y = by * 4 + py
                    if y >= height:
                        continue
                    for px in range(4):
                        x = bx * 4 + px
                        if x >= width:
                            continue
                        p = pixels[py * 4 + px]
                        o = (y * width + x) * 4
                        out[o] = p[0]
                        out[o + 1] = p[1]
                        out[o + 2] = p[2]
                        out[o + 3] = 255
    return bytes(out)


def psnr_rgb(a: bytes, b: bytes, width: int, height: int,
             alpha_threshold: int = -1) -> dict:
    """RGB PSNR / max error between two top-down RGBA8 buffers.

    ``alpha_threshold`` >= 0 only scores pixels whose *source* alpha is at
    least the threshold.  ETC1A4 encoders may spend no bits on RGB hidden by
    zero alpha, so the all-pixel figure would punish invisible data; the
    visible figure is the one a renderer can actually show.  Both are reported
    by :func:`quality_report`.
    """
    if len(a) != len(b) or len(a) != width * height * 4:
        raise TextureError("PSNR buffers differ in size")
    mse = 0.0
    max_error = 0
    n = 0
    pixels = 0
    for i in range(0, len(a), 4):
        if alpha_threshold >= 0 and a[i + 3] < alpha_threshold:
            continue
        pixels += 1
        for c in range(3):
            d = int(a[i + c]) - int(b[i + c])
            if d < 0:
                d = -d
            if d > max_error:
                max_error = d
            mse += d * d
            n += 1
    if n == 0:
        return {"mse": 0.0, "psnr_db": None, "max_abs_error": 0,
                "pixels": 0, "skipped": True}
    mse /= n
    if mse == 0:
        psnr = None
    else:
        import math
        psnr = round(10.0 * math.log10((255.0 * 255.0) / mse), 3)
    return {
        "mse": round(mse, 4),
        "psnr_db": psnr,
        "max_abs_error": max_error,
        "pixels": pixels,
    }


def quality_report(source_rgba: bytes, decoded_rgba: bytes,
                   width: int, height: int) -> dict:
    """All-pixel and visible-pixel RGB quality for one encoded level."""
    out = {
        "all": psnr_rgb(source_rgba, decoded_rgba, width, height),
        "visible": psnr_rgb(source_rgba, decoded_rgba, width, height,
                            alpha_threshold=8),
        "alpha_psnr": None,
        "alpha_note": ("alpha is 4-bit in ETC1A4 (16 levels, step 17, max "
                       "round-trip error 8) and absent in ETC1; the preview/"
                       "raw planes do not expose a stable alpha ordering, so "
                       "alpha is reported analytically rather than as PSNR"),
    }
    return out



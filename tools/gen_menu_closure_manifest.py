#!/usr/bin/env python3
"""Generate the d3d9_menu_closure_manifest.h table from the closure manifest.

The JSON manifest stays the single source of truth.  This generator refuses to
emit a header when a required bytecode entry lacks a stage/key/SHA-256 or when
the opcode names are not part of the D3D9 SM2/SM3 instruction set.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
LIVE_TOOLS = Path(r"C:\Users\vasya\Documents\Skyrim_N3DS\tools")
if (REPO / "source" / "d3d9_com.c").exists():
    TOOLS = HERE                     # applied inside the repository
    HEADER_DIR = REPO / "source"
else:
    TOOLS = LIVE_TOOLS               # scratch tree, reuse the repo's parser
    HEADER_DIR = REPO / "runtime"
if str(TOOLS) not in sys.path:
    sys.path.insert(0, str(TOOLS))

from skyrim.shaders import OPCODES  # noqa: E402

OPCODE_BY_NAME = {name: op for op, name in OPCODES.items()}
REG_PREFIX = {"v": 1, "s": 2, "o": 6, "r": 3, "c": 2}
FIXED_STATE_ORDER = (
    "texture_units", "sampler", "vertex_color", "filter", "blend",
    "depth_test", "depth_write", "alpha_test", "tev_stages", "tev_stages_max",
)


def fail(msg: str) -> None:
    raise SystemExit("gen_menu_closure_manifest: " + msg)


def c_ident(text: str) -> str:
    out = []
    for ch in text.upper():
        out.append(ch if ch.isalnum() else "_")
    ident = "".join(out)
    while "__" in ident:
        ident = ident.replace("__", "_")
    return ident.strip("_")


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse_key(text):
    if text is None:
        return (0, 0)
    if isinstance(text, int):
        return (int(text), 1)
    if isinstance(text, str):
        return (int(text, 16), 1)
    fail("bad key %r" % (text,))


def reg_type_of(register: str) -> int:
    return REG_PREFIX.get(register[:1], 0)


def fixed_state_text(state: dict) -> str:
    parts = []
    for key in FIXED_STATE_ORDER:
        if key in state:
            value = state[key]
            parts.append("%s=%s" % (key, "1" if value is True else
                                    "0" if value is False else value))
    for key in sorted(state):
        if key not in FIXED_STATE_ORDER:
            value = state[key]
            parts.append("%s=%s" % (key, "1" if value is True else
                                    "0" if value is False else value))
    return " ".join(parts)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest",
                    default=str(HERE / "menu_closure_manifest.json"))
    ap.add_argument("--out",
                    default=str(HEADER_DIR / "d3d9_menu_closure_manifest.h"))
    args = ap.parse_args(argv)

    raw = Path(args.manifest).read_bytes()
    manifest = json.loads(raw)
    if manifest.get("kind") != "first_main_menu_shader_closure":
        fail("unexpected manifest kind")

    entries = manifest["entries"]
    vs = manifest.get("vs_family") or {}
    required_ids = {"menu.logo.ps", "menu.composite.ps", "menu.fog.fixed",
                    "menu.generic.vs"}
    present = {e["id"] for e in entries}
    if vs.get("id"):
        present.add(vs["id"])
    missing = sorted(required_ids - present)
    if missing:
        fail("manifest is missing required closure entries: %s" %
             ", ".join(missing))
    for e in entries:
        if e["id"] in required_ids and not e.get("required"):
            fail("%s must stay required:true in the manifest" % e["id"])
    if vs and not vs.get("required"):
        fail("%s must stay required:true in the manifest" % vs["id"])
    out = []
    w = out.append

    w("/* Generated by tools/gen_menu_closure_manifest.py -- do not edit.")
    w(" * Source: menu_closure_manifest.json")
    w(" * Manifest SHA-256: %s" % hashlib.sha256(raw).hexdigest())
    w(" */")
    w("#pragma once")
    w("#include <stdint.h>")
    w("")
    w("#define D9_MENU_CLOSURE_MANIFEST_SHA256 %s" % c_string(hashlib.sha256(raw).hexdigest()))
    w("#define D9_MENU_CLOSURE_GENERATED 1")
    w("")

    # Stable entry ids.  Keep the order of the JSON manifest and append the VS
    # family after the fixed entries so future manifest edits only append.
    w("enum {")
    w("    D9_MENU_ENTRY_NONE = -1,")
    ids = {}
    for i, e in enumerate(entries):
        ident = "D9_MENU_ENTRY_" + c_ident(e["id"])
        ids[e["id"]] = i
        w("    %s = %d, /* %s */" % (ident, i, e["id"]))
    if vs:
        ident = "D9_MENU_ENTRY_" + c_ident(vs["id"])
        ids[vs["id"]] = len(entries)
        w("    %s = %d, /* %s */" % (ident, len(entries), vs["id"]))
    w("    D9_MENU_ENTRY_COUNT = %d" % (len(entries) + (1 if vs else 0)))
    w("};")
    w("")

    decl_rows = []
    opcode_rows = []
    entry_rows = []

    def emit_decls(entry_id: str, rows):
        flat = []
        for r in rows:
            usage_name = r["usage"]
            if usage_name not in ("position", "blendweight", "blendindices",
                                  "normal", "psize", "texcoord", "tangent",
                                  "binormal", "tessfactor", "positiont",
                                  "color", "fog", "depth", "sample"):
                fail("%s: unknown usage %r" % (entry_id, usage_name))
            usage = {
                "position": 0, "blendweight": 1, "blendindices": 2,
                "normal": 3, "psize": 4, "texcoord": 5, "tangent": 6,
                "binormal": 7, "tessfactor": 8, "positiont": 9, "color": 10,
                "fog": 11, "depth": 12, "sample": 13,
            }[usage_name]
            register = r.get("register")
            reg_type = reg_type_of(register) if register else 255
            reg_index = int(register[1:]) if register and register[1:].isdigit() else 0
            tex = int(r["texture_type"]) if "texture_type" in r else -1
            flat.append((usage, int(r.get("usage_index", 0)), reg_type,
                         reg_index, tex))
        return flat

    for e in entries:
        kind = {"ps": 0, "vs": 1, "fixed": 2}[e["stage"]]
        required = 1 if e.get("required") else 0
        runtime_gated = 0 if e["stage"] == "fixed" else 1
        if e["stage"] == "fixed":
            if e.get("bytecode", "missing") is not None:
                fail("%s: fixed entry must declare bytecode: null" % e["id"])
            if not e.get("state"):
                fail("%s: fixed entry needs a state contract" % e["id"])
            if not e.get("why_no_fxp"):
                fail("%s: fixed entry needs why_no_fxp" % e["id"])
            key_known, key, version = 0, 0, 0
            chunk_bytes = instructions = texld = branches = 0
            sha = b"\x00" * 32
            decls = []
            ops = []
        else:
            key, key_known = parse_key(e.get("key"))
            sha_hex = e.get("sha256")
            if e["id"] in ids and e["id"] != vs.get("id"):
                if not sha_hex or len(sha_hex) != 64:
                    fail("%s: bytecode entry needs a 64-hex SHA-256" % e["id"])
            sha = bytes.fromhex(sha_hex) if sha_hex else b"\x00" * 32
            version = {"ps_3_0": 0xFFFF0300, "vs_3_0": 0xFFFE0300}.get(
                e.get("version"))
            if version is None:
                fail("%s: unsupported version %r" % (e["id"], e.get("version")))
            chunk_bytes = int(e.get("chunk_bytes") or 0)
            instructions = int(e.get("instruction_count") or 0)
            texld = int(e.get("texture_samples") or 0)
            branches = int(e.get("branches") or 0)
            if not chunk_bytes or not instructions:
                fail("%s: bytecode entry needs chunk_bytes and instruction_count"
                     % e["id"])
            decls = emit_decls(e["id"], e.get("required_declarations") or [])
            ops = []
            for name in e.get("opcode_sequence") or []:
                if name not in OPCODE_BY_NAME:
                    fail("%s: unknown opcode name %r" % (e["id"], name))
                ops.append(OPCODE_BY_NAME[name])
        entry_rows.append({
            "id": e["id"], "kind": kind, "required": required,
            "runtime_gated": runtime_gated, "key_known": key_known, "key": key,
            "chunk_bytes": chunk_bytes, "version": version,
            "instructions": instructions, "texld": texld, "branches": branches,
            "sha": sha, "decls": decls, "ops": ops,
            "fixed_state": fixed_state_text(e.get("state") or {}) if e["stage"] == "fixed" else None,
            "why_no_fxp": e.get("why_no_fxp"),
        })

    if vs:
        version = {"vs_3_0": 0xFFFE0300}.get(vs.get("version"))
        if version is None:
            fail("vs_family: unsupported version %r" % (vs.get("version")))
        decls = emit_decls(vs["id"], vs.get("required_declarations") or [])
        mask = 0
        for idx in vs.get("required_outputs") or []:
            mask |= 1 << int(idx)
        entry_rows.append({
            "id": vs["id"], "kind": 1, "required": 1 if vs.get("required") else 0,
            "runtime_gated": 1, "key_known": 0, "key": 0,
            "chunk_bytes": 0, "version": version, "instructions": 0,
            "texld": -1, "branches": -1,
            "sha": b"\x00" * 32, "decls": decls, "ops": [], "output_mask": mask,
            "fixed_state": None, "why_no_fxp": None,
        })

    # Declaration and opcode backing arrays.
    for i, row in enumerate(entry_rows):
        if row["decls"]:
            w("static const D9MenuClosureDecl d9_menu_decls_%d[] = {" % i)
            for (usage, index, reg_type, reg_index, tex) in row["decls"]:
                w("    {%d, %d, %d, %d, %d}," % (usage, index, reg_type,
                                                 reg_index, tex))
            w("};")
        if row["ops"]:
            w("static const uint16_t d9_menu_ops_%d[] = {%s};"
              % (i, ", ".join(str(op) for op in row["ops"])))
        if row["sha"] and any(row["sha"]):
            hexbytes = ", ".join("0x%02x" % b for b in row["sha"])
            w("static const uint8_t d9_menu_sha_%d[32] = {%s};" % (i, hexbytes))
    w("")

    w("static const D9MenuClosureEntry d9_menu_closure_entries[D9_MENU_ENTRY_COUNT] = {")
    for i, row in enumerate(entry_rows):
        sha_ref = "d9_menu_sha_%d" % i if any(row["sha"]) else "0"
        decls_ref = "d9_menu_decls_%d" % i if row["decls"] else "0"
        ops_ref = "d9_menu_ops_%d" % i if row["ops"] else "0"
        fixed = c_string(row["fixed_state"]) if row["fixed_state"] else "0"
        why = c_string(row["why_no_fxp"]) if row["why_no_fxp"] else "0"
        w("    [%d] = {" % i)
        w("        .id = %s," % c_string(row["id"]))
        w("        .stage = %du, .required = %du, .runtime_gated = %du,"
          % (row["kind"], row["required"], row["runtime_gated"]))
        w("        .key_known = %du, .key = 0x%08xu," % (row["key_known"], row["key"]))
        w("        .chunk_bytes = %du, .version = 0x%08xu," % (row["chunk_bytes"], row["version"]))
        w("        .instruction_count = %du, .texld_count = %d, .branch_count = %d,"
          % (row["instructions"], row["texld"], row["branches"]))
        w("        .sha256 = %s," % sha_ref)
        w("        .declarations = %s, .declaration_count = %du,"
          % (decls_ref, len(row["decls"])))
        w("        .opcodes = %s, .opcode_count = %du,"
          % (ops_ref, len(row["ops"])))
        w("        .required_output_mask = 0x%08xu," % row.get("output_mask", 0))
        w("        .fixed_state = %s," % fixed)
        w("        .why_no_fxp = %s," % why)
        w("    },")
    w("};")
    w("")

    Path(args.out).write_text("\n".join(out) + "\n")
    print("wrote %s (%d entries)" % (args.out, len(entry_rows)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

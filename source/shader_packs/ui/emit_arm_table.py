#!/usr/bin/env python3
"""Emit the BSA UI PICA VS table fragment for an ARM compile-only check.

The table is *derived metadata*: ids, SHA-256 pins and the embedded picasso
`.shbin` bytes of the 15 emitted-verified programs.  It lives in this pack's
`generated/` directory and is compiled with devkitARM (no link) to prove the
emitted-program table is valid C for the ARM11 build.

    python source\\shader_packs\\ui\\emit_arm_table.py
    arm-none-eabi-gcc -c -march=armv6k -mfloat-abi=hard \
        source/shader_packs/ui/generated/ui_vs_table_check.c -o build/ui_vs.o
"""

from __future__ import annotations

import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PLANS = os.path.join(HERE, "plans.json")
GENERATED = os.path.join(HERE, "generated")
INC = os.path.join(GENERATED, "ui_vs_table.inc")
CHECK = os.path.join(GENERATED, "ui_vs_table_check.c")


def main() -> int:
    with open(PLANS, encoding="utf-8") as handle:
        entries = [entry for entry in json.load(handle)["entries"]
                   if entry.get("id", "").startswith("ui.vs.")
                   and entry.get("codegen") == "emitted-verified"]
    blobs, rows = [], []
    for index, entry in enumerate(entries):
        emitter = entry["emitter"]
        path = os.path.join(HERE, emitter["shbin"])
        with open(path, "rb") as handle:
            blob = handle.read()
        digest = hashlib.sha256(blob).hexdigest()
        if digest != emitter["shbin_sha256"]:
            raise SystemExit("%s: pinned SHA-256 mismatch" % entry["id"])
        symbol = "d9_ui_vs_blob_%d" % index
        blobs.append(("_Alignas(4) static const uint8_t %s[%d] = {"
                      % (symbol, len(blob)), blob))
        rows.append((entry, symbol, len(blob)))

    lines = ["/* Generated by source/shader_packs/ui/emit_arm_table.py.",
             " * Derived metadata + embedded picasso blobs; do not edit. */"]
    for head, blob in blobs:
        lines.append(head)
        for start in range(0, len(blob), 16):
            lines.append("    " + ",".join(
                "0x%02x" % byte for byte in blob[start:start + 16]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const D9UiVsProgram d9_ui_vs_programs[] = {")
    for entry, symbol, size in rows:
        emitter = entry["emitter"]
        lines.append('    {"%s", "%s", "%s", %s, %du, %uu, %uu, %uu},'
                     % (entry["id"], entry["sha256"],
                        emitter["shbin_sha256"], symbol, size,
                        emitter["instructions"], emitter["uniform_rows"],
                        len(entry["inputs"])))
    lines.append("};")
    lines.append("#define D9_UI_VS_PROGRAM_COUNT "
                 "(sizeof(d9_ui_vs_programs) / sizeof(d9_ui_vs_programs[0]))")
    lines.append("")
    with open(INC, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(lines))

    check = """/* Compile-only check for the emitted BSA UI PICA VS table. */
#include <stdint.h>

typedef struct {
    const char *id;
    const char *sha256;
    const char *shbin_sha256;
    const uint8_t *bytes;
    unsigned size;
    unsigned instructions;
    unsigned uniform_rows;
    unsigned input_count;
} D9UiVsProgram;

#include "ui_vs_table.inc"

unsigned d9_ui_vs_program_count(void)
{
    return (unsigned)D9_UI_VS_PROGRAM_COUNT;
}
"""
    with open(CHECK, "w", encoding="ascii", newline="\n") as handle:
        handle.write(check)
    print("wrote %s (%d programs) and %s" % (INC, len(rows), CHECK))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Emit the runtime PICA VS table for the BSA UI pack.

Writes, from the committed `plans.json` and the pinned `.shbin` files:

* ``source/d3d9_pica_vs_ui_shbin.inc`` — `_Alignas(4)` embedded picasso bytes;
* ``source/d3d9_pica_vs_ui_table.inc`` — `D9PicaVsProgram` rows;
* ``tests/ui_vs_shbin_sizes.inc`` — actual byte counts for the host test.

Only ``codegen == "emitted-verified"`` entries with a pinned `.shbin` are
emitted.  The lookup/count functions in ``source/d3d9_pica_vs.c`` include the
table next to the skin and GFx menu rows.

    python source\\shader_packs\\ui\\emit_runtime_tables.py
    arm-none-eabi-gcc -c -O2 -std=gnu11 -march=armv6k -mfloat-abi=hard \\
        -Isource source/d3d9_pica_vs.c -o ui_pica_vs.o
"""

from __future__ import annotations

import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
PLANS = os.path.join(HERE, "plans.json")
SHBIN_INC = os.path.join(REPO, "source", "d3d9_pica_vs_ui_shbin.inc")
TABLE_INC = os.path.join(REPO, "source", "d3d9_pica_vs_ui_table.inc")
SIZES_INC = os.path.join(REPO, "tests", "ui_vs_shbin_sizes.inc")

#: D3D usage name -> (attribute enum, declaration type, loader count, format).
ATTRS = {
    "position": ("D9_PICA_VS_ATTR_POSITION", "D9_DECL_FLOAT3", 3,
                 "D9_PICA_VS_FMT_FLOAT"),
    "texcoord": ("D9_PICA_VS_ATTR_TEXCOORD", "D9_DECL_FLOAT2", 2,
                 "D9_PICA_VS_FMT_FLOAT"),
    "color": ("D9_PICA_VS_ATTR_COLOR", "D9_DECL_UBYTE4N", 4,
              "D9_PICA_VS_FMT_UBYTE_NORM"),
}
ORDER = {"position": 0, "texcoord": 1, "color": 2}


def _attrs(entry):
    rows = []
    for item in sorted(entry["inputs"], key=lambda i: ORDER.get(
            i["usage_name"], 99)):
        usage = item["usage_name"]
        if usage not in ATTRS:
            raise SystemExit("%s: no attribute mapping for %r"
                             % (entry["id"], usage))
        attr, kind, comps, fmt = ATTRS[usage]
        rows.append((attr, kind, comps, fmt, item["reg_index"]))
    return rows


def main() -> int:
    with open(PLANS, encoding="utf-8") as handle:
        entries = [e for e in json.load(handle)["entries"]
                   if e["id"].startswith("ui.vs.")
                   and e.get("codegen") == "emitted-verified"]
    entries.sort(key=lambda e: e["id"])

    shbin_lines = [
        "/* Generated by source/shader_packs/ui/emit_runtime_tables.py.",
        " * Embedded picasso .shbin bytes for the BSA UI PICA VS.  Do not edit. */",
        "",
    ]
    table_lines = [
        "/* Generated by source/shader_packs/ui/emit_runtime_tables.py.",
        " * Verified emitted BSA UI PICA VS; exact vs_3_0 SHA-256 only. */",
        "static const D9PicaVsProgram d9_pica_vs_ui_entries[] = {",
    ]
    sizes_lines = [
        "/* Generated by source/shader_packs/ui/emit_runtime_tables.py.",
        " * Actual embedded .shbin byte counts of the BSA UI PICA VS. */",
        "static const struct { const char *sha256; unsigned bytes; }",
        "d9_ui_vs_shbin_sizes[] = {",
    ]
    for entry in entries:
        emitter = entry["emitter"]
        path = os.path.join(HERE, emitter["shbin"])
        with open(path, "rb") as handle:
            blob = handle.read()
        digest = hashlib.sha256(blob).hexdigest()
        if digest != emitter["shbin_sha256"]:
            raise SystemExit("%s: pinned .shbin SHA-256 mismatch" % entry["id"])
        if entry["emitter"]["bones"] != 0:
            raise SystemExit("%s: UI program must use the identity bank"
                             % entry["id"])
        sym = "d9_pica_vs_ui_shbin_%s" % entry["sha256"][:8]
        shbin_lines.append("_Alignas(4) static const uint8_t %s[%u] = {"
                           % (sym, len(blob)))
        for start in range(0, len(blob), 12):
            chunk = ",".join("0x%02x" % b for b in blob[start:start + 12])
            shbin_lines.append("    " + chunk + ",")
        shbin_lines += ["};", ""]
        sizes_lines.append('    {"%s", %uu},' % (entry["sha256"], len(blob)))
        attrs = _attrs(entry)
        table_lines += [
            "    {",
            '        "%s",' % entry["id"],
            '        "%s",' % entry["sha256"],
            '        "%s.v.pica",' % entry["id"],
            '        "%s.shbin",' % entry["id"],
            '        "%s",' % emitter["shbin_sha256"],
            "        %s, %u," % (sym, len(blob)),
            "        %uu, %uu, 0u, 0u, %uu," % (
                emitter["instructions"], emitter["uniform_rows"],
                emitter["uniform_rows"]),
            "        %uu," % len(attrs),
            "        {",
        ]
        for attr, kind, comps, fmt, reg in attrs:
            table_lines.append("        {%s, %s, %d, %s, %du},"
                               % (attr, kind, comps, fmt, reg))
        table_lines += ["        },", "    },"]
    table_lines += [
        "};",
        "#define D9_PICA_VS_UI_ENTRY_COUNT "
        "(sizeof(d9_pica_vs_ui_entries)/sizeof(d9_pica_vs_ui_entries[0]))",
        "",
    ]
    sizes_lines += [
        "};",
        "#define D9_UI_VS_SHIBIN_SIZE_COUNT "
        "(sizeof(d9_ui_vs_shbin_sizes)/sizeof(d9_ui_vs_shbin_sizes[0]))",
        "",
    ]
    for path, lines in ((SHBIN_INC, shbin_lines), (TABLE_INC, table_lines),
                        (SIZES_INC, sizes_lines)):
        with open(path, "w", encoding="ascii", newline="\n") as handle:
            handle.write("\n".join(lines))
    print("wrote %s, %s and %s (%d programs)"
          % (SHBIN_INC, TABLE_INC, SIZES_INC, len(entries)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

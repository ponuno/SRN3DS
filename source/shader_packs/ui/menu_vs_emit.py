#!/usr/bin/env python3
"""Emit and verify PICA200 VS programs for the GFx StartMenu vertex shaders.

Scope: the five unique full-blob ``vs_3_0`` programs in the measured GFx
catalogue (``TESV.exe`` table ``0x12dfca8``).  These are *not* skinned: the
body is a 4-row ``dp4`` matrix transform (position), optional ``dp4`` texgen
pairs (c4/c5 and c6/c7) and ``mov`` passthrough of the declared colours.

This module is deliberately separate from ``skinning/pica_vs_emit.py`` so the
skin palette path keeps its own contract.  It re-uses that module's D3D IR
interpreter, PICА interpreter and picasso runner as libraries; it does not
change the skin plans or the skin runtime table.

PICA limits are recorded, not hidden:

* ``position``, ``color`` and ``texcoord0..2`` are the only output semantics
  picasso accepts.  There is exactly one primary colour output, so a program
  that writes ``color0`` *and* ``color1`` (``0975cc50``, ``73904d3f``) cannot
  be represented and is a named refusal.
* PICA clip space is ``[y, -x, z-w, w]``; the emitted code remaps the D3D
  position exactly like the skin emitter does.

Verification: 256 deterministic samples, D3D IR vs emitted PICA words, with
``max |dpos| <= 1e-4`` and every varying bit-exact within the same bound.
Only a passing numeric run plus a non-empty picasso ``.shbin`` produces
``codegen = emitted-verified``.

Run: ``python source/shader_packs/ui/menu_vs_emit.py`` (defaults to
``F:\\Skyrim\\TESV.exe``; set ``TESV`` to override).
"""

from __future__ import annotations

import hashlib
import json
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__).replace("\\", "/"))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
for _path in (REPO, os.path.join(REPO, "tools"),
              os.path.join(REPO, "tools", "shaders"),
              os.path.join(REPO, "source", "shader_packs", "skinning"),
              HERE):
    if _path not in sys.path:
        sys.path.insert(0, _path)

import pica_vs_emit as S  # noqa: E402  (skin verifier, reused as a library)
import menu_plan_tool as M  # noqa: E402
from shaders import compile as C, asm  # noqa: E402

PLANS = os.path.join(HERE, "plans.json")
GENERATED = os.path.join(HERE, "generated")
TABLE = os.path.join(REPO, "source", "d3d9_pica_vs_menu_table.inc")
SHBIN = os.path.join(REPO, "source", "d3d9_pica_vs_menu_shbin.inc")
REPORT = os.path.join(HERE, "menu_vs_report.json")
TESV_CANDIDATES = [r"F:\Skyrim\TESV.exe",
                   r"E:\census_ir2\ir_container\_work\ir_container_input.bin"]
SAMPLES = 256
TOLERANCE = 1e-4
SWZ = "xyzw"

OUT_NAME = {0: "outpos", 5: "outtc0", 10: "outclr"}
OUT_TEX = {0: "outtc0", 1: "outtc1", 2: "outtc2"}
# Declared simplification: PICA can carry one primary colour.  A GFx program
# that also writes color1 is emitted without it; the plan records exactly what
# was dropped and is never labelled exact.
SIMPLIFIED_DROP = {10: (1, 2, 3, 4)}


def is_dropped(item: dict) -> bool:
    return (item["usage"] == 10
            and item["usage_index"] in SIMPLIFIED_DROP.get(10, ()))


def approximation_text(plan: dict) -> str:
    dropped = sorted({item["usage_name"] + str(item["usage_index"])
                      for item in plan["outputs"] if is_dropped(item)})
    if not dropped:
        return ""
    return ("PICA single primary colour: dropped vertex %s output(s); "
            "colour0 is kept, color1/alpha tint is not applied"
            % ", ".join(dropped))


class Refusal(Exception):
    pass


def load_ir(tesv: str) -> dict:
    """Full-blob SHA-256 -> IR for the five GFx VS programs."""
    pe = M.PE(tesv)
    rows = M.read_table(pe, M.VS_TABLE_VA, M.VS_TABLE_SLOTS)
    out = {}
    for row in rows:
        if row["full_sha256"] in out:
            continue
        ir = C.build_ir(row["blob"])
        if ir.error:
            raise Refusal("parse_%s: %s" % (row["full_sha256"][:8], ir.error))
        out[row["full_sha256"]] = ir
    return out


def out_name(item: dict) -> str:
    if item["usage"] == 0:
        return "outpos"
    if item["usage"] == 5:
        name = OUT_TEX.get(item["usage_index"])
        if name is None:
            raise Refusal("texcoord%d_output_unmapped" % item["usage_index"])
        return name
    if item["usage"] == 10 and item["usage_index"] == 0:
        return "outclr"
    raise Refusal("color%d_output_unmapped (PICA has one primary colour output)"
                  % item["usage_index"])


def emit(plan: dict, ir: C.IR) -> str:
    outputs = {}
    for item in plan["outputs"]:
        if is_dropped(item):
            continue
        outputs[(item["type"], item["reg_index"])] = out_name(item)
    if len(set(outputs.values())) != len(outputs):
        raise Refusal("two D3D outputs collapse onto one PICA output")

    lines = [
        "; Generated by source/shader_packs/ui/menu_vs_emit.py",
        "; plan %s  sha256 %s" % (plan["id"], plan["sha256"]),
        "; GFx menu VS: dp4 matrix rows + texgen + two mov passthroughs.",
        "; No bone palette, no relative constants, no loops or branches.",
    ]
    seen = set()
    for item in plan["outputs"]:
        if is_dropped(item):
            continue
        name = out_name(item)
        if name in seen:
            continue
        seen.add(name)
        if item["usage"] == 0:
            semantic = "position"
        elif item["usage"] == 5:
            semantic = "texcoord%d" % item["usage_index"]
        else:
            semantic = "color"
        lines.append(".out %s %s" % (name, semantic))
    lines += ["", ".proc main"]

    def operand(src) -> str:
        if src.reg_type == asm.REG_INPUT:
            base = "v%d" % src.index
        elif src.reg_type == asm.REG_CONST and not src.relative:
            base = "c%d" % src.index
        else:
            raise Refusal("opcode_%s_source_type_%d_unsupported"
                          % (ins.name, src.reg_type))
        text = base + ("" if src.swizzle == "xyzw" else "." + src.swizzle)
        return ("-" + text) if src.modifier == 1 else text

    for ins in ir.body:
        if ins.name in ("def", "nop"):
            continue
        dst = ins.dst
        if dst is None or dst.reg_type not in (asm.REG_OUTPUT, asm.REG_RASTOUT,
                                               asm.REG_ATTROUT, asm.REG_COLOROUT):
            raise Refusal("opcode_%s_destination_%d_unsupported"
                          % (ins.name, dst.reg_type if dst else -1))
        target = outputs.get((dst.reg_type, dst.index))
        if target is None:
            # A dropped color1 output has no PICA semantic; skip its write.
            if any(item["reg_index"] == dst.index and is_dropped(item)
                   for item in plan["outputs"]):
                continue
            raise Refusal("output_%d_unmapped" % dst.index)
        mask = "".join(SWZ[i] for i in range(4) if dst.mask & (1 << i))
        if not mask:
            raise Refusal("instruction_without_destination_mask")
        dest = target + ("" if mask == "xyzw" else "." + mask)
        ops = [operand(src) for src in ins.srcs]
        if ins.name == "dp4":
            if len(ops) != 2:
                raise Refusal("dp4_arity_%d" % len(ops))
            # picasso wants the register as the second source; the constant
            # may be first.
            a, b = ops
            const = a.startswith(("c", "-c"))
            if const:
                lines.append("    dp4 %s, %s, %s" % (dest, a, b))
            else:
                lines.append("    dp4 %s, %s, %s" % (dest, b, a))
        elif ins.name == "mov":
            if len(ops) != 1:
                raise Refusal("mov_arity_%d" % len(ops))
            lines.append("    mov %s, %s" % (dest, ops[0]))
        else:
            raise Refusal("unsupported_opcode_%s" % ins.name)

    # D3D clip space -> PICA [y, -x, z-w, w], as in d9_pica_transform().
    if any(item["usage"] == 0 for item in plan["outputs"]):
        lines += [
            "    mov r15, outpos",
            "    mov outpos.x, r15.yyyy",
            "    mov outpos.y, -r15.xxxx",
            "    add outpos.z, r15.zzzz, -r15.wwww",
            "    mov outpos.w, r15.wwww",
        ]
    lines += ["    end", ".end", ""]
    return "\n".join(lines)


def build_sample(rng, plan):
    inputs = {}
    for item in plan["inputs"]:
        reg, usage = item["reg_index"], item["usage"]
        if usage == 0:
            inputs[reg] = [rng.uniform(-5, 5) for _ in range(3)] + [1.0]
        elif usage in (5, 10):
            inputs[reg] = [rng.random() for _ in range(4)]
        else:
            raise Refusal("sample_input_%s" % item["usage_name"])
    return inputs


def build_constants(rng, rows):
    consts = {}
    for row in range(rows):
        # Distinct matrix rows: a wrong constant row cannot hide as equality.
        consts[row] = [rng.uniform(-2, 2) for _ in range(4)]
    return consts


def verify(plan, ir, text, samples=SAMPLES):
    rows = 0
    for item in plan["inputs"]:
        for ins in ir.body:
            for src in ins.srcs:
                if src.reg_type == asm.REG_CONST:
                    rows = max(rows, src.index + 1)
    if rows != plan["uniform_registers"]:
        raise Refusal("uniform_rows_%d != plan_%d" % (rows, plan["uniform_registers"]))
    rng = random.Random(0x6D45 + int(plan["sha256"][:8], 16))
    max_pos = 0.0
    max_var = 0.0
    for _ in range(samples):
        inputs = build_sample(rng, plan)
        consts = build_constants(rng, rows)
        ref = S.interpret_ir(ir, inputs, consts, {})
        emitted = S.interpret_pica(text, inputs, consts, {})
        for item in plan["outputs"]:
            if is_dropped(item):
                continue
            name = out_name(item)
            a = list(ref.get(item["reg_index"], [0.0] * 4))
            if item["usage"] == 0:
                a = S.pica_clip(a)
            b = emitted.get(name, [0.0] * 4)
            mask = range(4)
            if item["usage"] == 5:
                mask = range(2)
            error = max(abs(a[i] - b[i]) for i in mask)
            if item["usage"] == 0:
                max_pos = max(max_pos, error)
            else:
                max_var = max(max_var, error)
    picasso, shbin = S.run_picasso(text)
    words = 0
    if len(shbin) >= 0x1C:
        words = int.from_bytes(shbin[0x18:0x1C], "little")
    ok = (samples > 0 and max_pos <= TOLERANCE and max_var <= TOLERANCE
          and picasso == "pass" and len(shbin) >= 0x30 and words > 0)
    return {
        "samples": samples, "tolerance": TOLERANCE,
        "max_abs_position": max_pos, "max_abs_varying": max_var,
        "picasso": picasso, "shbin_bytes": len(shbin), "instructions": words,
        "shbin": shbin,
    }, ok


def attrs_for(plan, ir):
    inputs = {}
    for item in plan["inputs"]:
        inputs[item["usage"]] = item["reg_index"]
    attrs = []
    order = [0, 5, 10]
    for usage in order:
        if usage not in inputs:
            continue
        if usage == 0:
            attrs.append(("D9_PICA_VS_ATTR_POSITION", "D9_DECL_FLOAT3", 3,
                          "D9_PICA_VS_FMT_FLOAT", inputs[usage]))
        elif usage == 5:
            attrs.append(("D9_PICA_VS_ATTR_TEXCOORD", "D9_DECL_FLOAT2", 2,
                          "D9_PICA_VS_FMT_FLOAT", inputs[usage]))
        elif usage == 10:
            attrs.append(("D9_PICA_VS_ATTR_COLOR", "D9_DECL_UBYTE4N", 4,
                          "D9_PICA_VS_FMT_UBYTE_NORM", inputs[usage]))
    return attrs


def emit_tables(entries):
    sizes_path = os.path.join(REPO, "tests", "menu_vs_shbin_sizes.inc")
    sizes_lines = [
        "/* Generated by source/shader_packs/ui/menu_vs_emit.py.",
        " * Actual embedded .shbin byte counts of the GFx menu VS.  Do not edit. */",
        "static const struct { const char *sha256; unsigned bytes; }",
        "d9_menu_vs_shbin_sizes[] = {",
    ]
    shbin_lines = [
        "/* Generated by source/shader_packs/ui/menu_vs_emit.py.",
        " * Embedded picasso .shbin bytes for the GFx menu VS.  Do not edit. */",
        "",
    ]
    table_lines = [
        "/* Generated by source/shader_packs/ui/menu_vs_emit.py.",
        " * Verified emitted GFx menu PICA VS; exact vs_3_0 SHA-256 only. */",
        "static const D9PicaVsProgram d9_pica_vs_menu_entries[] = {",
    ]
    for entry in entries:
        sym = "d9_pica_vs_menu_shbin_%s" % entry["sha256"][:8]
        blob = entry["shbin"]
        sizes_lines.append('    {"%s", %uu},' % (entry["sha256"], len(blob)))
        shbin_lines.append("static const uint8_t %s[%u] = {" % (sym, len(blob)))
        for start in range(0, len(blob), 12):
            chunk = ",".join("0x%02x" % b for b in blob[start:start + 12])
            shbin_lines.append("    " + chunk + ",")
        shbin_lines.append("};")
        shbin_lines.append("")
        table_lines += [
            "    {",
            '        "%s",' % entry["id"],
            '        "%s",' % entry["sha256"],
            '        "%s.v.pica",' % entry["id"],
            '        "%s.shbin",' % entry["id"],
            '        "%s",' % entry["shbin_sha256"],
            "        %s, %u," % (sym, len(blob)),
            "        %uu, %uu, 0u, 0u, %uu," % (
                entry["instructions"], entry["uniform_rows"],
                entry["uniform_rows"]),
            "        %uu," % len(entry["attrs"]),
            "        {",
        ]
        for attr, kind, comps, fmt, reg in entry["attrs"]:
            table_lines.append(
                "        {%s, %s, %d, %s, %du}," % (
                    attr, kind, comps, fmt, reg))
        table_lines += ["        },", "    },"]
    table_lines.append("};")
    table_lines.append("#define D9_PICA_VS_MENU_ENTRY_COUNT "
                       "(sizeof(d9_pica_vs_menu_entries)/sizeof(d9_pica_vs_menu_entries[0]))")
    table_lines.append("")
    sizes_lines.append("};")
    sizes_lines.append("#define D9_MENU_VS_SHIBIN_SIZE_COUNT "
                       "(sizeof(d9_menu_vs_shbin_sizes)/sizeof(d9_menu_vs_shbin_sizes[0]))")
    sizes_lines.append("")
    with open(sizes_path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(sizes_lines))
    with open(SHBIN, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(shbin_lines))
    with open(TABLE, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(table_lines))


def main(argv=None):
    tesv = os.environ.get("TESV") or next(
        (p for p in TESV_CANDIDATES if os.path.exists(p)), "")
    if not tesv:
        print("REFUSED: retail TESV.exe not found; set TESV", file=sys.stderr)
        return 2
    irs = load_ir(tesv)
    with open(PLANS, encoding="utf-8") as handle:
        doc = json.load(handle)
    os.makedirs(GENERATED, exist_ok=True)

    emitted = []
    results = []
    for entry in doc["entries"]:
        if entry["stage"] != "vs_3_0":
            continue
        ir = irs.get(entry["sha256"])
        if ir is None:
            raise Refusal("bytecode_for_%s_not_found" % entry["sha256"][:12])
        try:
            text = emit(entry, ir)
            report, ok = verify(entry, ir, text)
        except Refusal as exc:
            entry["codegen"] = "refused"
            entry["runtime"] = 0
            entry["draw_enabled"] = 0
            entry["quality"] = "exact"
            entry["note"] = ("PICA VS refusal: %s; CreateVertexShader keeps "
                             "the plan-selected object and the draw gate "
                             "refuses by name" % exc)
            results.append({"id": entry["id"], "status": "refused",
                            "reason": str(exc)})
            continue
        if not ok:
            raise Refusal("numeric_verification_failed_%s" % entry["id"])
        entry["codegen"] = "emitted-verified"
        entry["runtime"] = 1
        entry["draw_enabled"] = 1
        approx = approximation_text(entry)
        entry["quality"] = "approx" if approx else "exact"
        if approx:
            entry["approximation"] = approx
        else:
            entry.pop("approximation", None)
        entry["note"] = (
            ("GFx menu VS emitted and verified against the declared simplified "
             "spec (%s): 256 samples, max |dpos| %.1e, picasso pass"
             % (approx, report["max_abs_position"]))
            if approx else
            ("GFx menu VS emitted and verified: dp4 matrix/texgen rows, "
             "256 samples, max |dpos| %.1e, picasso pass"
             % report["max_abs_position"]))
        entry["emitter"] = {
            "asm": "generated/%s.v.pica" % entry["id"],
            "shbin": "generated/%s.shbin" % entry["id"],
            "shbin_sha256": hashlib.sha256(report["shbin"]).hexdigest(),
            "shbin_bytes": report["shbin_bytes"],
            "samples": report["samples"], "tolerance": report["tolerance"],
            "max_abs_position": report["max_abs_position"],
            "max_abs_varying": report["max_abs_varying"],
            "picasso": report["picasso"],
            # bone_rows == 0 is the menu contract: identity c0..cN bank.
            "bones": 0,
            "uniform_rows": entry["uniform_registers"],
            "instructions": report["instructions"],
            "inputs": [{"usage": i["usage"], "usage_name": i["usage_name"],
                        "reg_index": i["reg_index"]} for i in entry["inputs"]],
            "uniforms": [{"row": row, "d3d": row}
                         for row in range(entry["uniform_registers"])],
        }
        entry["emitted_asm"] = "generated/%s.v.pica" % entry["id"]
        with open(os.path.join(GENERATED, "%s.v.pica" % entry["id"]),
                  "w", encoding="ascii", newline="\n") as handle:
            handle.write(text)
        with open(os.path.join(GENERATED, "%s.shbin" % entry["id"]),
                  "wb") as handle:
            handle.write(report["shbin"])
        emitted.append({
            "id": entry["id"], "sha256": entry["sha256"],
            "shbin": report["shbin"], "instructions": report["instructions"],
            "uniform_rows": entry["uniform_registers"],
            "attrs": attrs_for(entry, ir),
            "shbin_sha256": entry["emitter"]["shbin_sha256"],
        })
        results.append({"id": entry["id"], "status": "pass",
                        "max_abs_position": report["max_abs_position"],
                        "max_abs_varying": report["max_abs_varying"],
                        "picasso": report["picasso"]})

    vs = [e for e in doc["entries"] if e["stage"] == "vs_3_0"]
    doc["coverage"]["vs"] = {
        "draw": sum(e["draw_enabled"] for e in vs),
        "refused": sum(1 for e in vs if e.get("codegen") == "refused"),
        "translated": len(vs),
        "emitted": sum(1 for e in vs
                       if e.get("codegen") == "emitted-verified"),
    }
    doc["coverage"]["draw_enabled"] = sum(e["draw_enabled"]
                                          for e in doc["entries"])
    with open(PLANS, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(doc, handle, indent=1, sort_keys=True)
        handle.write("\n")
    emit_tables(emitted)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as handle:
        json.dump({"schema": "ui-menu-vs-emitter/1", "samples": SAMPLES,
                   "tolerance": TOLERANCE, "entries": results},
                  handle, indent=1, sort_keys=True)
        handle.write("\n")
    for row in results:
        print("%-22s %-7s pos=%s var=%s picasso=%s" % (
            row["id"], row["status"],
            "%.3g" % row["max_abs_position"] if "max_abs_position" in row else "-",
            "%.3g" % row["max_abs_varying"] if "max_abs_varying" in row else "-",
            row.get("picasso", row.get("reason", "-"))))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Refusal as exc:
        print("REFUSED: %s" % exc, file=sys.stderr)
        raise SystemExit(2)
